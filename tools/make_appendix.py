"""Stage 4c: appendix tables, generated from the code and the stored results (no hand-typed values).

    python tools/make_appendix.py [--paper paper]

A  tab_hyper.tex          every hyperparameter per model, from malcert/config.py (full preset) and run_all.py
B  tab_attack.tex         attack and certification settings, from config.py and malcert/attacks.py
D  tab_family_rule.tex    coverage of T_f(t) before (95% intervals) and after the 2h-revision interval rule
E  tab_grouping_val.tex   grouping candidates on the validation split (results_grouping_val/val_configs.csv)
F  tab_tuning.tex         tuning grids, grouped 3-fold CV means, chosen settings (results_tuning/)
F  tab_per_seed.tex       main metrics per family-split seed (tools/stats.per_seed)
"""
import argparse, json, os, re, sys
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT); sys.path.insert(0, os.path.join(ROOT, "tools"))
from malcert.config import get_config                     # noqa: E402
import stats                                              # noqa: E402


def tab(cols, head, rows, note=""):
    T = ["\\begin{tabular}{" + cols + "}", "\\toprule", head + " \\\\", "\\midrule"]
    T += [r if isinstance(r, str) else " & ".join(r) + " \\\\" for r in rows]
    return "\n".join(T + ["\\bottomrule", "\\end{tabular}"] + ([f"% {note}"] if note else []))


def code_kwargs(pattern):
    """Keyword constants of a call in run_all.py, e.g. the LightGBM baseline: {'n_estimators': '500', ...}."""
    src = open(os.path.join(ROOT, "run_all.py"), encoding="utf-8").read()
    m = re.search(pattern, src, re.S)
    return dict(re.findall(r"(\w+)=([\w.]+)", m.group(0)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--paper", default=os.path.join(ROOT, "paper"))
    a = ap.parse_args()
    T = os.path.join(a.paper, "tables")
    c = get_config("full")
    hid = lambda h: "2381--" + "--".join(map(str, h)) + "--2"
    lgb = code_kwargs(r"gbm = lgb\.LGBMClassifier\([^)]*\)")
    lgv = code_kwargs(r"g = lgb\.LGBMClassifier\([^)]*\)")
    abl = {n: (p, k, e) for n, p, k, e in c.ablation_configs}
    sec = "\\midrule\\multicolumn{2}{l}{\\emph{%s}} \\\\"
    rows = [
        sec % "All neural networks",
        ["Optimizer", f"Adam, weight decay {c.weight_decay:g}, cosine learning-rate schedule"],
        ["Learning rate; batch size", f"{c.lr:g}; {c.batch_size}"],
        sec % "Standard MLP, PGD-AT, MLP views",
        ["Architecture; epochs", f"{hid(c.hidden)}; {c.epochs}"],
        ["PGD-AT", f"$\\epsilon={c.at_eps:g}$ on $B_\\epsilon$, {c.at_steps} PGD steps per batch"],
        sec % "Group ablation",
        ["Main", f"{abl['main'][0]}, $k={abl['main'][1]}$, MLP views {abl['main'][2] or c.epochs} epochs"],
        ["Second", f"{abl['second'][0]}, $k={abl['second'][1]}$, MLP views {abl['second'][2] or c.epochs} epochs"],
        ["EMBER groups", f"9 groups, $k={abl['ember'][1]}$, MLP views {abl['ember'][2] or c.epochs} epochs"],
        ["LightGBM views (main; second)",
         "; ".join(f"{n} trees, {l} leaves" for n, l in c.lgbm_view_params) + f", learning rate {lgv.get('learning_rate')}"],
        sec % "LightGBM baselines",
        ["LightGBM, monotonic LightGBM", f"{lgb.get('n_estimators')} trees, {lgb.get('num_leaves')} leaves, "
                                         f"learning rate {lgb.get('learning_rate')}; monotonic: +1 on the increase-only features"],
        sec % "Certified training (CROWN-IBP)",
        ["Architecture; epochs", f"{hid(c.ibp_hidden)}; {c.ibp_epochs}"],
        ["Schedule", f"{c.ibp_warmup} clean warm-up epochs, then budget ramp over {c.ibp_ramp} epochs; "
                     "$\\kappa$: 1$\\to$0.5, $\\beta$: 1$\\to$0"],
        ["Uniform ball; constrained box", f"$\\epsilon_{{\\text{{train}}}}={c.unc_train_eps:g}$; ${c.box_train_eps:g}$"],
        ["Edit-aware", f"$t_{{\\text{{train}}}}={c.edit_t_train:g}$, {c.edit_agg} over the four families"],
        ["Certification budgets", ", ".join(f"{e:g}" for e in c.cert_eps_list) + "; $T_f(t)$ at $t\\in\\{" +
         ", ".join(f"{t:g}" for t in c.family_scales) + "\\}$"],
        sec % "Smoothing baselines",
        ["Isotropic", "$\\sigma\\in\\{" + ", ".join(f"{s:g}" for s in c.sigmas) + "\\}$, trained with the same noise"],
        ["Giri et al.\\ re-implementation", f"$\\sigma={c.giri_sigma:g}$, each EMBER group dropped with probability {c.giri_drop:g}"],
    ]
    rows[0] = rows[0].replace("\\midrule", "", 1)          # the header rule already separates the first block
    open(os.path.join(T, "tab_hyper.tex"), "w").write(tab("lp{0.62\\linewidth}", "Setting & Value", rows,
                                                          "generated by tools/make_appendix.py from malcert/config.py (full preset) and run_all.py"))

    rows = [
        ["PGD on $B_\\epsilon$", f"{c.pgd_steps} steps, step size $2.5\\epsilon/{c.pgd_steps}$, {c.pgd_restarts} restart(s), "
                                 "uniform random start in $B_\\epsilon$, projection after every step"],
        ["PGD budgets", ", ".join(f"{e:g}" for e in c.eps_list) + f"; {c.n_attack_points} test malware attacked"],
        ["Group transplant", f"{c.group_attack_points} test malware, {c.group_attack_donors} benign donors, up to "
                             f"$r={c.group_attack_max_r}$ groups of the {c.grouping} partition, greedy"],
        ["Smoothing CERTIFY", f"$n_0={c.n0}$ selection and $n={c.n_cert:,}$ certification samples per point, "
                              f"$\\alpha={c.alpha:g}$, Clopper--Pearson bound; abstain if the bound is $\\le 0.5$; every test point"],
    ]
    open(os.path.join(T, "tab_attack.tex"), "w").write(tab("lp{0.68\\linewidth}", "Procedure & Settings", rows))

    v1 = pd.read_csv(os.path.join(ROOT, "ps_results", "family_coverage_v1.csv")).set_index("family")
    v2 = pd.read_csv(os.path.join(ROOT, "ps_results", "family_coverage.csv")).set_index("family")
    ts = [x for x in v2.columns if x.startswith("cov_t")]
    rows = [[f.replace("F_", ""), str(int(v1.loc[f, "support"])), str(int(v2.loc[f, "support"]))] +
            [f"{100 * v1.loc[f, t]:.1f} / {100 * v2.loc[f, t]:.1f}" for t in ts] for f in v2.index]
    open(os.path.join(T, "tab_family_rule.tex"), "w").write(tab(
        "lrr" + "r" * len(ts), "Family & Support (95\\%) & Support (final) & " +
        " & ".join(f"$t={t[5:]}$" for t in ts), rows,
        "eval-half coverage (%), 95%-interval rule / final rule (log 2-25)"))

    G = pd.read_csv(os.path.join(ROOT, "results_grouping_val", "val_configs.csv"))
    sel = json.load(open(os.path.join(ROOT, "results_grouping_val", "selection.json")))["selected"]
    rows = [[r.partition + (" (selected)" if (r.partition, r.k) == (sel["partition"], sel["k"]) else ""), str(r.k),
             str(r.G), str(r.attackable), str(r.views), str(r.ceiling), f"{100 * r.val_acc:.1f}", f"{100 * r.val_fpr:.1f}",
             f"{100 * r.score:.1f}", str(r.n_types_certified), "yes" if r.eligible else "no",
             f"{100 * r.exact_minus_bound_max:.2f}"] for r in G.itertuples()]
    open(os.path.join(T, "tab_grouping_val.tex"), "w").write(tab(
        "lrrrrrrrrrrr", "Grouping & $k$ & $G$ & Attackable & Views & Ceiling & Acc. & FPR & Score & Types & Eligible & "
                        "Exact $-$ bound", rows, "validation split, seed 0, quick budgets (log 2-3, 2-4)"))

    ch = json.load(open(os.path.join(ROOT, "results_tuning", "chosen.json")))["chosen"]
    MOD = [("mlp", "MLP", ["lr", "epochs"]), ("lgbm_main", "LightGBM views, main", ["n_estimators", "num_leaves"]),
           ("lgbm_second", "LightGBM views, second", ["n_estimators", "num_leaves"]),
           ("abl_second_mlp", "MLP views, second", ["epochs"]), ("crown_unc", "CROWN-IBP, uniform ball", ["eps"]),
           ("crown_box", "CROWN-IBP, constrained box", ["eps"]), ("crown_edit", "CROWN-IBP, edit-aware", ["t_train", "agg"])]
    rows = []
    for key, lab, ps in MOD:
        D = pd.read_csv(os.path.join(ROOT, "results_tuning", f"{key}.csv"))
        for r in D.itertuples():
            setting = ", ".join(f"{p.replace('_', ' ')} {getattr(r, p):g}" if not isinstance(getattr(r, p), str)
                                else f"{p.replace('_', ' ')} {getattr(r, p)}" for p in ps)
            chosen = all(str(getattr(r, p)) == str(ch[key][p]) or
                         (not isinstance(getattr(r, p), str) and float(getattr(r, p)) == float(ch[key][p])) for p in ps)
            cert = f"{100 * r.cert:.1f}" if hasattr(r, "cert") else "--"
            rows.append([lab if r.Index == 0 else "", setting + (" $\\ast$" if chosen else ""),
                         f"{100 * r.val_acc:.1f}", f"{100 * r.val_fpr:.2f}", cert])
        rows.append("\\addlinespace")
    open(os.path.join(T, "tab_tuning.tex"), "w").write(tab(
        "llrrr", "Model & Setting & Acc. & FPR & Certified", rows[:-1],
        "grouped 3-fold CV over train + validation of the seed-0 family split; fold means; * = chosen (log 2-30, 2-33)"))

    P = stats.per_seed(["results_family", "results_family_s34"])
    COLS = [("acc_lightgbm", "LightGBM acc."), ("acc_abl_lgbm_main", "LGBM views acc."),
            ("cert_r1_abl_lgbm_main", "LGBM views cert. $r=1$"), ("cert_edits_abl_main", "MLP views, 9 types"),
            ("certT1_crown_edit", "Edit-aware $T_f(1)$"), ("cert005_crown_box", "Box, $\\epsilon=0.05$"),
            ("cert005_crown_unc", "Uniform, $\\epsilon=0.05$")]
    rows = [[str(s)] + [f"{100 * P.loc[s, m]:.1f}" for m, _ in COLS] for s in P.index]
    open(os.path.join(T, "tab_per_seed.tex"), "w").write(tab(
        "r" + "r" * len(COLS), "Seed & " + " & ".join(l for _, l in COLS), rows,
        "family split; seed 0's training families were used for tuning (log 2-30)"))
    # C: the per-unit annotation table (problem_space.py) as a longtable, which can break across pages
    L = open(os.path.join(T, "tab_annotation_full.tex"), encoding="utf-8").read().splitlines()
    i_mid = L.index("\\midrule")
    head = L[1:i_mid + 1]
    body = [x for x in L[i_mid + 1:] if x not in ("\\bottomrule", "\\end{tabular}") and not x.startswith("%")]
    cols = L[0][len("\\begin{tabular}"):]
    out = (["\\begin{longtable}" + cols,
            "\\caption{Feature annotation per unit: kind, status in the draft and after the repair, the rule and the edits "
            "that changed the unit, and the reference.}\\label{tab:annfull}\\\\"] + head + ["\\endfirsthead"] + head +
           ["\\endhead"] + body + ["\\bottomrule", "\\end{longtable}"])
    open(os.path.join(T, "tab_annotation_long.tex"), "w", encoding="utf-8").write("\n".join(out))
    print("appendix tables written")


if __name__ == "__main__":
    main()
