"""Stage 3b leakage audit (REVISION_PLAN 3b; no training).

    python tools/leakage_audit.py [--out results_leakage]

All of BODMAS: exact duplicate feature vectors, label conflicts among them, duplicate hashes.
Seed 0 of the random and of the family split: test rows with an exact twin in training, share of test malware
whose family also occurs in training, share of test samples with a training neighbour within L2 0.1 in
standardised space (malware, benign), median nearest-neighbour distance.
Writes <out>/leakage.json and paper/tables/numbers_leak.tex (prefix Leak).
"""
import argparse, hashlib, json, os, sys
import numpy as np
import torch

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from malcert.config import get_config                                     # noqa: E402
from malcert.data import Preprocessor, load_subset, split_indices         # noqa: E402

NEAR = 0.1


def row_hashes(X):
    return np.array([hashlib.sha1(r.tobytes()).hexdigest() for r in np.ascontiguousarray(X)])


def nn_dist(Xte, Xtr, dev):
    A, B = torch.as_tensor(Xte, device=dev), torch.as_tensor(Xtr, device=dev)
    out = []
    with torch.no_grad():
        for a in range(0, len(A), 256):
            out.append(torch.cat([torch.cdist(A[a:a + 256], B[b:b + 16384]).min(1).values[:, None]
                                  for b in range(0, len(B), 16384)], 1).min(1).values.cpu())
    return torch.cat(out).numpy()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="results_leakage")
    ap.add_argument("--paper", default=os.path.join(ROOT, "paper"))
    a = ap.parse_args()
    os.chdir(ROOT)
    os.makedirs(a.out, exist_ok=True)
    cfg = get_config("full")
    import pandas as pd
    d = np.load(cfg.data_npz)
    X, y = d["X"], d["y"]
    h = row_hashes(X)
    del X
    _, inv, cnt = np.unique(h, return_inverse=True, return_counts=True)
    dup_rows = int((cnt[inv] > 1).sum())
    conflict = 0
    for g in np.where(cnt > 1)[0]:
        conflict += int(len(set(y[inv == g])) > 1)
    meta = pd.read_csv(cfg.meta_csv)
    out = dict(bodmas_rows=int(len(y)), duplicate_vector_rows=dup_rows, duplicate_vector_groups=int((cnt > 1).sum()),
               groups_with_label_conflict=conflict, duplicate_sha256=int(meta["sha"].duplicated().sum()))
    dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    for split in ("random", "family"):
        c = get_config("full", split=split)
        data = load_subset(c, seed=0)
        sp = split_indices(data, c, seed=0)
        hs = row_hashes(data["X"])
        tr_h = set(hs[sp["tr"]])
        twin = np.array([x in tr_h for x in hs[sp["te"]]])
        yte = data["y"][sp["te"]]
        fam_tr = set(data["family"][sp["tr"]][data["y"][sp["tr"]] == 1])
        fam_te = data["family"][sp["te"]][yte == 1]
        pp = Preprocessor().fit(data["X"][sp["tr"]])
        dist = nn_dist(pp.transform(data["X"][sp["te"]]), pp.transform(data["X"][sp["tr"]]), dev)
        out[split] = dict(test_rows_with_exact_twin=int(twin.sum()),
                          test_malware_family_in_train=float(np.mean([f in fam_tr for f in fam_te])),
                          near_twin_malware=float((dist[yte == 1] <= NEAR).mean()),
                          near_twin_benign=float((dist[yte == 0] <= NEAR).mean()),
                          median_nn_malware=float(np.median(dist[yte == 1])), median_nn_benign=float(np.median(dist[yte == 0])))
        print(split, out[split], flush=True)
    json.dump(out, open(os.path.join(a.out, "leakage.json"), "w"), indent=1)
    print({k: v for k, v in out.items() if not isinstance(v, dict)})
    N = {"LeakDupRows": str(dup_rows), "LeakDupConflicts": str(conflict), "LeakDupSha": str(out["duplicate_sha256"])}
    for split, k in (("random", "Rand"), ("family", "Fam")):
        o = out[split]
        N[f"Leak{k}Twins"] = str(o["test_rows_with_exact_twin"])
        N[f"Leak{k}FamOverlap"] = f"{100 * o['test_malware_family_in_train']:.1f}"
        N[f"Leak{k}NearMal"] = f"{100 * o['near_twin_malware']:.1f}"
        N[f"Leak{k}NearBen"] = f"{100 * o['near_twin_benign']:.1f}"
    with open(os.path.join(a.paper, "tables", "numbers_leak.tex"), "w") as f:
        f.write("% auto-generated by tools/leakage_audit.py -- do not edit by hand\n")
        for k, v in N.items():
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")


if __name__ == "__main__":
    main()
